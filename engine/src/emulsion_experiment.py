def _cie_1931_xyz_approx(wavelength_nm: np.ndarray) -> np.ndarray:
    """Smooth analytic approximation to the CIE 1931 2-degree observer."""
    wavelength_nm = wavelength_nm.astype(np.float64)

    def asymmetric_gaussian(mu: float, left: float, right: float) -> np.ndarray:
        sigma = np.where(wavelength_nm < mu, left, right)
        return np.exp(-0.5 * np.square((wavelength_nm - mu) / sigma))

    x_bar = (
        1.056 * asymmetric_gaussian(599.8, 37.9, 31.0)
        + 0.362 * asymmetric_gaussian(442.0, 16.0, 26.7)
        - 0.065 * asymmetric_gaussian(501.1, 20.4, 26.2)
    )
    y_bar = (
        0.821 * asymmetric_gaussian(568.8, 46.9, 40.5)
        + 0.286 * asymmetric_gaussian(530.9, 16.3, 31.1)
    )
    z_bar = (
        1.217 * asymmetric_gaussian(437.0, 11.8, 36.0)
        + 0.681 * asymmetric_gaussian(459.0, 26.0, 13.8)
    )
    return np.stack([x_bar, y_bar, z_bar], axis=1).astype(np.float32)


def _blackbody_spd(wavelength_nm: np.ndarray, temperature_k: float) -> np.ndarray:
    """Relative Planck spectrum for a xenon-projection white approximation."""
    wavelength_m = wavelength_nm.astype(np.float64) * 1e-9
    c2 = 1.438776877e-2
    spd = 1.0 / (
        np.power(wavelength_m, 5.0)
        * np.expm1(c2 / (wavelength_m * temperature_k))
    )
    return (spd / np.max(spd)).astype(np.float32)


def _print_2383_analytical_amount_axes(
    status_a_axis: np.ndarray,
) -> list[np.ndarray]:
    """Invert separated principal Status-A densities to analytical dye amount.

    The print H-D curves are integral Status-A measurements: each principal
    reading already contains the selected dye's unwanted absorption through the
    measurement product.  Before combining the three published dye spectra,
    invert each separated principal response.  This avoids applying that
    unwanted absorption twice and remains nonlinear through toe and shoulder.
    """
    dye_spectra = np.stack(
        [
            np.interp(
                PRINT_STATUS_A_WAVELENGTHS_NM,
                PRINT_DYE_WAVELENGTHS_NM,
                PRINT_DYE_CMY_SPECTRAL_DENSITY[:, channel],
            )
            for channel in range(3)
        ],
        axis=1,
    ).astype(np.float64)
    weights = PRINT_STATUS_A_RGB_WEIGHTS.astype(np.float64)
    weight_sums = np.sum(weights, axis=0)
    amount_axis = np.linspace(0.0, 14.0, 28001, dtype=np.float64)
    result: list[np.ndarray] = []
    for channel in range(3):
        spectral_density = amount_axis[:, None] * dye_spectra[None, :, channel]
        transmission = np.power(10.0, -np.clip(spectral_density, 0.0, 20.0))
        measured = np.einsum(
            "...w,w->...", transmission, weights[:, channel]
        )
        principal_density = -np.log10(
            np.maximum(measured / weight_sums[channel], 1e-12)
        )
        result.append(
            np.interp(
                np.maximum(
                    np.asarray(status_a_axis, dtype=np.float64)
                    - float(PRINT_2383_STATUS_A_DMIN_RGB[channel]),
                    0.0,
                ),
                principal_density,
                amount_axis,
            ).astype(np.float32)
        )
    return result


def build_2383_projection_lut(size: int = 25) -> np.ndarray:
    """Integrate analytical 2383 CMY dye amounts under plotted xenon."""
    axis = np.linspace(0.0, PRINT_2383_DMAX, size, dtype=np.float32)
    analytical_axes = _print_2383_analytical_amount_axes(axis)
    cyan, magenta, yellow = np.meshgrid(
        *analytical_axes, indexing="ij"
    )
    cmy = np.stack([cyan, magenta, yellow], axis=-1).reshape(-1, 3)

    cmf = _cie_1931_xyz_approx(PRINT_DYE_WAVELENGTHS_NM)
    illuminant = KODAK_XENON_PROJECTOR_RELATIVE_SPD
    weighted_cmf = illuminant[:, None] * cmf
    white_xyz = np.sum(weighted_cmf, axis=0)
    d65_xyz = np.array([0.95047, 1.0, 1.08883], dtype=np.float32)
    source_white = white_xyz / white_xyz[1]

    # Bradford chromatic adaptation preserves colour relationships better than
    # independently scaling X, Y and Z. The latter is not a chromatic adaptation
    # transform and contributed a small additional hue error in V13/V14.
    bradford = np.array(
        [
            [0.8951, 0.2664, -0.1614],
            [-0.7502, 1.7135, 0.0367],
            [0.0389, -0.0685, 1.0296],
        ],
        dtype=np.float32,
    )
    bradford_inverse = np.linalg.inv(bradford).astype(np.float32)
    source_cone = bradford @ source_white
    destination_cone = bradford @ d65_xyz
    adaptation = (
        bradford_inverse
        @ np.diag(destination_cone / np.maximum(source_cone, 1e-8))
        @ bradford
    ).astype(np.float32)

    # Some accelerated BLAS builds emit spurious floating-point status warnings
    # for these finite float32 matrices; the values are explicitly bounded.
    with np.errstate(all="ignore"):
        spectral_density = np.clip(
            cmy @ PRINT_DYE_CMY_SPECTRAL_DENSITY.T, 0.0, 16.0
        )
        transmission = np.power(10.0, -spectral_density)
        xyz = transmission @ weighted_cmf
        xyz /= white_xyz[1]
        xyz = xyz @ adaptation.T
        rgb = xyz @ XYZ_D65_TO_REC709.T
    return rgb.reshape(size, size, size, 3).astype(np.float32)


def apply_2383_callier_density(print_density_rgb: np.ndarray) -> np.ndarray:
    """Subtle collimated-projection density increase from 2383 light scatter.

    FilmLight documents separate scatter-corrected xenon calibrations for print
    stocks and notes that the Callier effect in colour film is subtle. Status-A
    density is therefore increased only about one percent through the useful
    scale, receding as the 2383 shoulder approaches maximum density.
    """
    net = np.maximum(print_density_rgb - PRINT_2383_DENSITY_RGB[:, 0], 0.0)
    shoulder_reduction = 1.0 - 0.65 * smoothstep(3.0, PRINT_2383_DMAX, net)
    return (
        print_density_rgb
        + net * shoulder_reduction * PRINT_2383_CALLIER_GAIN_RGB
    ).astype(np.float32)


def apply_typical_projection_flare(display_linear: np.ndarray) -> np.ndarray:
    """Apply optional room/projector flare; zero for the scene-referred master."""
    flare = TYPICAL_CINEMA_PROJECTION_FLARE
    return ((display_linear + flare) / (1.0 + flare)).astype(np.float32)


def calibrate_2383_h61_colour_patches(
    projected: np.ndarray,
    scan_reference: np.ndarray,
) -> np.ndarray:
    """Constrain projected RGB separations with an H-61-style colour check.

    Kodak's LAD procedure requires the red, green and blue patches to reproduce
    correctly as well as the gray strip. Public 5279/2383 data do not contain a
    measured TAF transform, so V15 uses the already balanced Spirit optical-film
    match as the separation reference. Projection lightness remains entirely
    from 2383; only opponent direction and a restrained chroma magnitude are
    calibrated. A real photographed 5279-to-2383 target can replace this anchor
    without changing the density, grain or projection model.
    """
    projected_lab = linear_rec709_to_oklab(projected)
    reference_lab = linear_rec709_to_oklab(scan_reference)
    projected_chroma = np.linalg.norm(projected_lab[..., 1:3], axis=-1)
    reference_chroma = np.linalg.norm(reference_lab[..., 1:3], axis=-1)

    projected_direction = projected_lab[..., 1:3] / np.maximum(
        projected_chroma[..., None], 1e-6
    )
    reference_direction = reference_lab[..., 1:3] / np.maximum(
        reference_chroma[..., None], 1e-6
    )
    # The Spirit reference is only a provisional H-61 hue aim. Earlier versions
    # copied its entire a/b vector, erasing the physical print's saturation and
    # making the two finished branches nearly identical. V21 corrects gross hue
    # rotation while retaining a bounded 2383 saturation signature.
    target_direction = (
        (1.0 - PRINT_H61_REFERENCE_HUE_WEIGHT)
        * projected_direction
        + PRINT_H61_REFERENCE_HUE_WEIGHT * reference_direction
    )
    target_direction /= np.maximum(
        np.linalg.norm(target_direction, axis=-1)[..., None], 1e-6
    )
    projected_saturation = projected_chroma / np.maximum(
        projected_lab[..., 0], 0.025
    )
    reference_saturation = reference_chroma / np.maximum(
        reference_lab[..., 0], 0.025
    )
    target_saturation = (
        (1.0 - PRINT_H61_REFERENCE_SATURATION_WEIGHT)
        * projected_saturation
        + PRINT_H61_REFERENCE_SATURATION_WEIGHT * reference_saturation
    )
    target_saturation = np.clip(
        target_saturation,
        0.90 * reference_saturation,
        1.20 * reference_saturation + 1e-5,
    )
    target_ab = (
        target_direction
        * (target_saturation * projected_lab[..., 0])[..., None]
    )

    # Do not impose a hue on neutral/near-neutral areas. The smooth transition
    # also keeps dye-cloud noise continuous around the gray axis.
    colour_weight = smoothstep(0.003, 0.025, reference_chroma)
    # If the reference is at its achromatic toe, retain the projected residual
    # rather than amplifying a direction from numerical noise.
    colour_weight *= smoothstep(0.001, 0.010, projected_chroma + reference_chroma)
    calibrated_lab = projected_lab.copy()
    calibrated_lab[..., 1:3] = (
        projected_lab[..., 1:3] * (1.0 - colour_weight[..., None])
        + target_ab * colour_weight[..., None]
    )
    return compress_oklab_chroma_to_rec709(
        oklab_to_linear_rec709(calibrated_lab)
    )


def apply_2383_projection_lut(
    print_density_rgb: np.ndarray, rows_per_stripe: int = 96
) -> np.ndarray:
    """Trilinearly sample the spectral 2383 projection LUT without huge RAM use."""
    global _PRINT_2383_PROJECTION_LUT
    if _PRINT_2383_PROJECTION_LUT is None:
        _PRINT_2383_PROJECTION_LUT = build_2383_projection_lut()
    lut = _PRINT_2383_PROJECTION_LUT
    size = lut.shape[0]
    result = np.empty_like(print_density_rgb, dtype=np.float32)

    # 2383 red/green/blue record densities form cyan/magenta/yellow dyes.
    for row0 in range(0, print_density_rgb.shape[0], rows_per_stripe):
        row1 = min(row0 + rows_per_stripe, print_density_rgb.shape[0])
        scaled = np.clip(
            print_density_rgb[row0:row1] * ((size - 1) / PRINT_2383_DMAX),
            0.0,
            size - 1.00001,
        )
        lower = np.floor(scaled).astype(np.int16)
        fraction = scaled - lower
        upper = np.minimum(lower + 1, size - 1)
        c0, m0, y0 = lower[..., 0], lower[..., 1], lower[..., 2]
        c1, m1, y1 = upper[..., 0], upper[..., 1], upper[..., 2]
        fc, fm, fy = fraction[..., 0:1], fraction[..., 1:2], fraction[..., 2:3]

        c00 = lut[c0, m0, y0] * (1.0 - fc) + lut[c1, m0, y0] * fc
        c01 = lut[c0, m0, y1] * (1.0 - fc) + lut[c1, m0, y1] * fc
        c10 = lut[c0, m1, y0] * (1.0 - fc) + lut[c1, m1, y0] * fc
        c11 = lut[c0, m1, y1] * (1.0 - fc) + lut[c1, m1, y1] * fc
        c0y = c00 * (1.0 - fy) + c01 * fy
        c1y = c10 * (1.0 - fy) + c11 * fy
        result[row0:row1] = c0y * (1.0 - fm) + c1y * fm
    return result


def neutralize_2383_projected_gray_scale(projected: np.ndarray) -> np.ndarray:
    """Apply the final neutral-scale calibration of print + lamp + observer.

    The published dye curves are a small peak-normalized graph, not measured
    spectral data. Matching only density 1.0 leaves visible hue drift elsewhere.
    A laboratory would measure the projected multi-step gray strip; this shaper
    makes the same luminance-dependent correction while preserving chroma
    differences away from the neutral axis.
    """
    global _PRINT_2383_VIEW_NEUTRAL_TABLE
    if _PRINT_2383_VIEW_NEUTRAL_TABLE is None:
        densities = np.linspace(0.0, PRINT_2383_DMAX, 257, dtype=np.float32)
        neutral_density = np.repeat(densities[:, None], 3, axis=1)[None, ...]
        neutral_density = apply_2383_callier_density(neutral_density)
        neutral_rgb = apply_2383_projection_lut(neutral_density)[0]
        neutral_rgb = np.maximum(neutral_rgb, 1e-8)
        neutral_luma = np.einsum(
            "...c,c->...", neutral_rgb, [0.2126, 0.7152, 0.0722]
        )
        factors = neutral_luma[:, None] / neutral_rgb
        order = np.argsort(neutral_luma)
        _PRINT_2383_VIEW_NEUTRAL_TABLE = (
            neutral_luma[order].astype(np.float32),
            np.clip(factors[order], 0.35, 2.50).astype(np.float32),
        )
    luma_axis, factor_table = _PRINT_2383_VIEW_NEUTRAL_TABLE
    luma = np.einsum("...c,c->...", np.maximum(projected, 0.0), [0.2126, 0.7152, 0.0722])
    corrected = np.empty_like(projected)
    for channel in range(3):
        factor = np.interp(luma, luma_axis, factor_table[:, channel])
        corrected[..., channel] = projected[..., channel] * factor
    return np.maximum(corrected, 0.0).astype(np.float32)


