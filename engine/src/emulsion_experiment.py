def run_json(command: list[str]) -> dict:
    result = subprocess.run(command, check=True, capture_output=True, text=True)
    return json.loads(result.stdout)


def probe_video(path: Path) -> tuple[int, int, str]:
    data = run_json(
        [
            "ffprobe",
            "-v",
            "error",
            "-select_streams",
            "v:0",
            "-show_entries",
            "stream=width,height,r_frame_rate",
            "-of",
            "json",
            str(path),
        ]
    )
    stream = data["streams"][0]
    return int(stream["width"]), int(stream["height"]), stream["r_frame_rate"]


def srgb_encode(linear: np.ndarray) -> np.ndarray:
    linear = np.clip(linear, 0.0, 1.0)
    return np.where(
        linear <= 0.0031308,
        12.92 * linear,
        1.055 * np.power(linear, 1.0 / 2.4) - 0.055,
    )


def srgb_decode(encoded: np.ndarray) -> np.ndarray:
    encoded = np.asarray(encoded, dtype=np.float32)
    return np.where(
        encoded <= 0.04045,
        encoded / 12.92,
        np.power((encoded + 0.055) / 1.055, 2.4),
    ).astype(np.float32)


def bt709_encode(linear: np.ndarray) -> np.ndarray:
    """Encode display-linear Rec.709 with the Rec.709 camera OETF."""
    linear = np.clip(linear, 0.0, 1.0)
    return np.where(
        linear < 0.018,
        4.5 * linear,
        1.099 * np.power(linear, 0.45) - 0.099,
    )


def bt709_decode(encoded: np.ndarray) -> np.ndarray:
    """Decode the Rec.709 OETF used by the tagged ProRes masters."""
    encoded = np.clip(encoded, 0.0, 1.0)
    return np.where(
        encoded < 0.081,
        encoded / 4.5,
        np.power((encoded + 0.099) / 1.099, 1.0 / 0.45),
    )


def bt1886_reference_encode(linear: np.ndarray) -> np.ndarray:
    """Encode normalized display light for a 100-nit Rec.709/BT.1886 master.

    The interchange reference uses an ideal zero-black mastering display, so
    ITU-R BT.1886 reduces to a 2.4-power EOTF.  The film/scan black floor is
    already present in ``linear``; this function does not add or crush one.
    """
    return np.power(np.clip(linear, 0.0, 1.0), 1.0 / 2.4).astype(np.float32)


def bt1886_reference_decode(encoded: np.ndarray) -> np.ndarray:
    return np.power(np.clip(encoded, 0.0, 1.0), 2.4).astype(np.float32)


