def multiscale_field(
    rng: np.random.Generator, height: int, width: int, cloud_sigma: float
) -> np.ndarray:
    """Generate a dye-cloud-like random field with fine and clustered structure."""
    fine = rng.standard_normal((height, width), dtype=np.float32)
    fine = cv2.GaussianBlur(fine, (0, 0), cloud_sigma, borderType=cv2.BORDER_REFLECT)

    small_h = max(2, height // 5)
    small_w = max(2, width // 5)
    clustered = rng.standard_normal((small_h, small_w), dtype=np.float32)
    clustered = cv2.resize(clustered, (width, height), interpolation=cv2.INTER_CUBIC)
    clustered = cv2.GaussianBlur(
        clustered, (0, 0), cloud_sigma * 2.0, borderType=cv2.BORDER_REFLECT
    )

    field = 0.82 * fine + 0.18 * clustered
    field -= float(field.mean())
    field /= float(field.std()) + 1e-6
    return field


def ordinary_overlay_grain(
    rendered: np.ndarray, frame_index: int, strength: float
) -> np.ndarray:
    """Conventional post-render monochrome grain for the control branch."""
    height, width = rendered.shape[:2]
    rng = np.random.default_rng(10_000 + frame_index)
    field = multiscale_field(rng, height, width, 0.35)
    luma = np.einsum("...c,c->...", rendered, [0.2126, 0.7152, 0.0722])
    amplitude = strength * (0.35 + 0.65 * np.sqrt(np.clip(1.0 - luma, 0.0, 1.0)))
    result = rendered + field[..., None] * amplitude[..., None]
    return np.clip(result, 0.0, 1.0)


def disk_kernel(radius: float) -> np.ndarray:
    extent = max(1, int(math.ceil(radius)))
    yy, xx = np.mgrid[-extent : extent + 1, -extent : extent + 1]
    kernel = ((xx * xx + yy * yy) <= radius * radius).astype(np.float32)
    kernel[extent, extent] = 1.0
    return kernel


def poisson_dye_cloud_layer(
    target: np.ndarray,
    rng: np.random.Generator,
    radius: float,
    optical_sigma: float,
    centre_density: float,
) -> np.ndarray:
    """Render an optically integrated Poisson dye-cloud population.

    The continuous Boolean model is microscopic and binary, but a scanner pixel
    integrates many evaluations of that field.  In the small-grain/high-density
    limit its sufficient statistic is a Poisson count of developed dye-cloud
    centres.  Convolving those counts with a cloud kernel and the observation
    aperture produces continuous optical density without an additive noise plate.
    """
    kernel = disk_kernel(radius)
    kernel /= float(kernel.sum())
    centre_rate = np.clip(target, 0.0, 1.0) * centre_density
    developed_centres = rng.poisson(centre_rate).astype(np.float32)
    density = cv2.filter2D(
        developed_centres, -1, kernel, borderType=cv2.BORDER_REFLECT
    ) / centre_density
    density = cv2.GaussianBlur(
        density, (0, 0), optical_sigma, borderType=cv2.BORDER_REFLECT
    )
    # Separate the measured noise-power spectrum from the stock's measured MTF.
    # The expected signal is removed here and reintroduced unchanged; a dedicated
    # 5279 MTF model below filters RGB signal with channel-specific calibration.
    expected = cv2.filter2D(target, -1, kernel, borderType=cv2.BORDER_REFLECT)
    expected = cv2.GaussianBlur(
        expected, (0, 0), optical_sigma, borderType=cv2.BORDER_REFLECT
    )
    return np.clip(target + (density - expected), 0.0, 1.0)


def binomial_dye_cloud_deviation(
    activation_probability: np.ndarray,
    rng: np.random.Generator,
    radius: float,
    optical_sigma: float,
    site_count: int,
    subpixel_offset: tuple[float, float] = (0.0, 0.0),
    sample_seed: int | None = None,
) -> np.ndarray:
    """Sample one finite fast/medium/slow silver-halide site population.

    Poisson counts are valid only while a small fraction of possible grains is
    exposed. A real sub-emulsion contains a finite population: once all sites
    are developable its stochastic activation variance must fall again. Binomial
    p(1-p) statistics supply that toe-to-shoulder behaviour without adding a
    post-render noise plate.
    """
    probability = np.clip(activation_probability, 0.0, 1.0).astype(np.float32)
    if BINOMIAL_SAMPLER_MODE == "striped_v25":
        if sample_seed is None:
            raise ValueError("striped V25 sampler requires an explicit seed")
        developed_fraction = _striped_binomial_sample(
            probability, site_count, sample_seed
        )
    else:
        developed_fraction = rng.binomial(site_count, probability).astype(np.float32)
    developed_fraction /= float(site_count)

    kernel = disk_kernel(radius)
    kernel /= float(kernel.sum())
    sampled = cv2.filter2D(
        developed_fraction, -1, kernel, borderType=cv2.BORDER_REFLECT
    )
    expected = cv2.filter2D(
        probability, -1, kernel, borderType=cv2.BORDER_REFLECT
    )
    sigma = max(optical_sigma, 0.05)
    sampled = cv2.GaussianBlur(
        sampled, (0, 0), sigma, borderType=cv2.BORDER_REFLECT
    )
    expected = cv2.GaussianBlur(
        expected, (0, 0), sigma, borderType=cv2.BORDER_REFLECT
    )
    deviation = (sampled - expected).astype(np.float32)
    offset_x, offset_y = subpixel_offset
    if abs(offset_x) > 1e-6 or abs(offset_y) > 1e-6:
        transform = np.array(
            [[1.0, 0.0, offset_x], [0.0, 1.0, offset_y]], dtype=np.float32
        )
        deviation = cv2.warpAffine(
            deviation,
            transform,
            (deviation.shape[1], deviation.shape[0]),
            flags=cv2.INTER_LINEAR,
            borderMode=cv2.BORDER_REFLECT,
        )
    return deviation


def _striped_binomial_sample(
    probability: np.ndarray,
    site_count: int,
    sample_seed: int,
) -> np.ndarray:
    """Sample fixed seeded row stripes, optionally in parallel.

    Every worker writes a disjoint slice and all filtering happens only after
    the slices have been reassembled.  There is therefore no spatial boundary
    approximation, and worker count cannot change the output realization.
    """
    global _BINOMIAL_EXECUTOR
    height = probability.shape[0]
    stripes = min(BINOMIAL_RANDOM_STRIPES, height)
    bounds = np.linspace(0, height, stripes + 1, dtype=np.int32)
    output = np.empty(probability.shape, dtype=np.float32)

    def sample_stripe(index: int) -> None:
        row0, row1 = int(bounds[index]), int(bounds[index + 1])
        stripe_rng = np.random.default_rng(
            np.random.SeedSequence([int(sample_seed), int(index)])
        )
        output[row0:row1] = stripe_rng.binomial(
            site_count, probability[row0:row1]
        ).astype(np.float32)

    workers = max(1, int(BINOMIAL_PARALLEL_WORKERS))
    if workers == 1 or stripes == 1:
        for stripe in range(stripes):
            sample_stripe(stripe)
    else:
        if _BINOMIAL_EXECUTOR is None:
            _BINOMIAL_EXECUTOR = concurrent.futures.ThreadPoolExecutor(
                max_workers=workers,
                thread_name_prefix="v25-binomial",
            )
        list(_BINOMIAL_EXECUTOR.map(sample_stripe, range(stripes)))
    return output


@functools.lru_cache(maxsize=256)
def filtered_kernel_power(
    radius: float,
    optical_sigma: float,
    aperture_radius: float,
    subpixel_offset: tuple[float, float] = (0.0, 0.0),
) -> float:
    """Noise-power gain through dye cloud, optics and Kodak's 48 um aperture."""
    extent = int(math.ceil(radius + 4.0 * optical_sigma + aperture_radius)) + 4
    size = 2 * extent + 1
    impulse = np.zeros((size, size), dtype=np.float32)
    impulse[extent, extent] = 1.0

    cloud = disk_kernel(radius)
    cloud /= float(cloud.sum())
    response = cv2.filter2D(
        impulse, -1, cloud, borderType=cv2.BORDER_CONSTANT
    )
    response = cv2.GaussianBlur(
        response,
        (0, 0),
        max(optical_sigma, 0.05),
        borderType=cv2.BORDER_CONSTANT,
    )
    offset_x, offset_y = subpixel_offset
    if abs(offset_x) > 1e-6 or abs(offset_y) > 1e-6:
        transform = np.array(
            [[1.0, 0.0, offset_x], [0.0, 1.0, offset_y]], dtype=np.float32
        )
        response = cv2.warpAffine(
            response,
            transform,
            (response.shape[1], response.shape[0]),
            flags=cv2.INTER_LINEAR,
            borderMode=cv2.BORDER_CONSTANT,
        )
    aperture = disk_kernel(aperture_radius)
    aperture /= float(aperture.sum())
    response = cv2.filter2D(
        response, -1, aperture, borderType=cv2.BORDER_CONSTANT
    )
    return float(np.sum(np.square(response)))


def subemulsion_activation_probabilities(
    log_exposure: np.ndarray,
) -> np.ndarray:
    """Return fast/medium/slow developable fractions for each RGB record."""
    centres = (
        SUBEMULSION_FAST_CENTRE_LOGE_RGB[:, None]
        + SUBEMULSION_SPEED_OFFSETS_LOGE[None, :]
    )
    widths = SUBEMULSION_TRANSITION_WIDTH_RGB[:, None]
    argument = (log_exposure[..., :, None] - centres) / widths
    argument = np.clip(argument, -16.0, 16.0)
    return (1.0 / (1.0 + np.exp(-argument))).astype(np.float32)


def _as_spatial_record_array(values: np.ndarray) -> tuple[np.ndarray, tuple[int, ...]]:
    """Temporarily give scalar/strip RGB records image-like spatial axes."""
    source = np.asarray(values, dtype=np.float32)
    source_shape = source.shape
    if source.shape[-1] != 3:
        raise ValueError("5279 record arrays must end in three colour records")
    if source.ndim == 1:
        source = source[None, None, :]
    elif source.ndim == 2:
        source = source[None, :, :]
    return source, source_shape


def develop_5279_record_density_from_log_exposure(
    log_exposure: np.ndarray,
) -> np.ndarray:
    """Develop fast/medium/slow layers with local DIR before summation.

    Published 5279 H-D values already include the uniform-field chemical
    response. We distribute that exact net density among marginal sublayers,
    then add only local reaction/diffusion departures and colour-separation
    interimage departures. A spatially uniform neutral field therefore remains
    bit-for-bit on the published three H-D curves.
    """
    work_log_exposure, source_shape = _as_spatial_record_array(log_exposure)
    base_density = record_densities_from_log_exposure(work_log_exposure)
    net_density = np.maximum(base_density - SENSITO_DMIN_RGB, 0.0)
    activations = subemulsion_activation_probabilities(work_log_exposure)
    layer_weight = activations * SUBEMULSION_CAPACITY_FRACTIONS[None, None, None, :]
    layer_weight /= np.maximum(np.sum(layer_weight, axis=-1, keepdims=True), 1e-8)
    layer_density = net_density[..., None] * layer_weight

    net_capacity = SENSITO_DENSITY_RGB[:, -1] - SENSITO_DMIN_RGB
    layer_capacity = net_capacity[:, None] * SUBEMULSION_CAPACITY_FRACTIONS[None, :]
    release = 1.0 - np.exp(
        -1.45 * layer_density / np.maximum(layer_capacity[None, None, ...], 1e-6)
    )

    neutral_log_exposure = np.mean(work_log_exposure, axis=-1, keepdims=True)
    neutral_log_exposure = np.repeat(neutral_log_exposure, 3, axis=-1)
    neutral_density = record_densities_from_log_exposure(neutral_log_exposure)
    neutral_net = np.maximum(neutral_density - SENSITO_DMIN_RGB, 0.0)
    neutral_activation = subemulsion_activation_probabilities(neutral_log_exposure)
    neutral_weight = (
        neutral_activation * SUBEMULSION_CAPACITY_FRACTIONS[None, None, None, :]
    )
    neutral_weight /= np.maximum(
        np.sum(neutral_weight, axis=-1, keepdims=True), 1e-8
    )
    neutral_layer_density = neutral_net[..., None] * neutral_weight
    neutral_release = 1.0 - np.exp(
        -1.45
        * neutral_layer_density
        / np.maximum(layer_capacity[None, None, ...], 1e-6)
    )

    native_scale = work_log_exposure.shape[1] / 5760.0
    receiver_marginal = np.clip(4.0 * activations * (1.0 - activations), 0.0, 1.0)
    correction = np.zeros_like(layer_density, dtype=np.float32)
    release_departure = release - neutral_release

    for source_record in range(3):
        for source_population in range(3):
            sigma = max(
                float(DIR_POPULATION_LATERAL_SIGMA_PX_5760[source_population])
                * native_scale,
                0.20,
            )
            deterministic_intralayer = float(
                DIR_DETERMINISTIC_INTRALAYER_STRENGTH_RGB[source_record]
            )
            if deterministic_intralayer != 0.0:
                source_release = release[..., source_record, source_population]
                diffused_release = cv2.GaussianBlur(
                    source_release, (0, 0), sigma, borderType=cv2.BORDER_REFLECT
                )
                # Local developer adjacency: inhibitor spills beyond a
                # developed edge and suppresses its less-exposed side, while a
                # uniform field has zero correction. V34 sets this duplicate
                # processed-MTF contribution to zero and skips the dead blur.
                correction[..., source_record, source_population] += (
                    deterministic_intralayer
                    * layer_capacity[source_record, source_population]
                    * (source_release - diffused_release)
                    * receiver_marginal[..., source_record, source_population]
                )

            diffused_departure = cv2.GaussianBlur(
                release_departure[..., source_record, source_population],
                (0, 0),
                sigma,
                borderType=cv2.BORDER_REFLECT,
            )
            for destination_record in range(3):
                record_transport = DIR_INTERIMAGE_RECEIVER_CAUSER[
                    destination_record, source_record
                ]
                if record_transport <= 0.0:
                    continue
                for destination_population in range(3):
                    transport = (
                        DIR_DEVELOPMENT_INTERIMAGE_STRENGTH
                        * record_transport
                        * DIR_POPULATION_TRANSPORT[
                            destination_population, source_population
                        ]
                        * DIR_POPULATION_RELEASE_GAIN[source_population]
                        * DIR_POPULATION_RECEIVER_GAIN[destination_population]
                    )
                    correction[..., destination_record, destination_population] -= (
                        transport
                        * layer_capacity[destination_record, destination_population]
                        * receiver_marginal[
                            ..., destination_record, destination_population
                        ]
                        * diffused_departure
                    )

    corrected_layers = np.clip(
        layer_density + correction,
        0.0,
        layer_capacity[None, None, ...] * 1.08,
    )
    developed = np.sum(corrected_layers, axis=-1) + SENSITO_DMIN_RGB
    return developed.reshape(source_shape).astype(np.float32)


def develop_5279_record_density(records: np.ndarray) -> np.ndarray:
    log_exposure = np.log10(np.maximum(records, 1e-8)) - 1.0
    return develop_5279_record_density_from_log_exposure(log_exposure)


def couple_5279_population_deviations(
    layer_deviation: np.ndarray,
    activations: np.ndarray,
    work_scale: float,
) -> np.ndarray:
    """Let sampled site development release spatially mobile inhibitor.

    This operates before dye-record mixing and density summation. Its expected
    value is zero, so the deterministic H-D curve is unchanged; the published
    post-process RMS normalization remains the final amplitude constraint.
    """
    coupled = np.asarray(layer_deviation, dtype=np.float32).copy()
    marginal = np.clip(4.0 * activations * (1.0 - activations), 0.0, 1.0)
    for source_record in range(3):
        for source_population in range(3):
            source = layer_deviation[..., source_record, source_population]
            sigma = max(
                float(DIR_POPULATION_LATERAL_SIGMA_PX_5760[source_population])
                * work_scale,
                0.20,
            )
            diffused = cv2.GaussianBlur(
                source, (0, 0), sigma, borderType=cv2.BORDER_REFLECT
            )
            coupled[..., source_record, source_population] += (
                DIR_STOCHASTIC_COUPLING_SCALE
                * DIR_DEVELOPMENT_INTRALAYER_STRENGTH_RGB[source_record]
                * (source - diffused)
                * marginal[..., source_record, source_population]
            )
            for destination_record in range(3):
                record_transport = DIR_INTERIMAGE_RECEIVER_CAUSER[
                    destination_record, source_record
                ]
                if record_transport <= 0.0:
                    continue
                for destination_population in range(3):
                    transport = (
                        DIR_STOCHASTIC_COUPLING_SCALE
                        * DIR_DEVELOPMENT_INTERIMAGE_STRENGTH
                        * record_transport
                        * DIR_POPULATION_TRANSPORT[
                            destination_population, source_population
                        ]
                        * DIR_POPULATION_RELEASE_GAIN[source_population]
                        * DIR_POPULATION_RECEIVER_GAIN[destination_population]
                    )
                    coupled[..., destination_record, destination_population] -= (
                        transport
                        * diffused
                        * marginal[..., destination_record, destination_population]
                    )
    return coupled.astype(np.float32)


def published_5279_granularity_sigma(
    log_exposure: np.ndarray,
) -> np.ndarray:
    """Interpolate Kodak's per-record post-process 48 um RMS density curves."""
    result = np.empty_like(log_exposure, dtype=np.float32)
    for channel in range(3):
        result[..., channel] = np.interp(
            log_exposure[..., channel],
            GRANULARITY_LOG_EXPOSURE,
            GRANULARITY_SIGMA_D_RGB[channel],
        ).astype(np.float32)
    return result


def form_5279_multilayer_record_density(
    records: np.ndarray,
    frame_index: int,
    grain_scale: float,
    oversample: int,
    precomputed_mean_density: np.ndarray | None = None,
) -> np.ndarray:
    """Form 5279 density from finite fast/medium/slow emulsion populations.

    The exact published H-D density remains the mean. Independent binomial site
    populations create the microscopic deviation in each colour record. Their
    relative sizes, speeds and coating capacities determine texture character;
    a final density-domain normalization makes a uniform patch reproduce Kodak's
    measured 48-micrometre RMS granularity curve rather than an arbitrary amount.
    """
    operator_profile = globals().get("_V27_STOCHASTIC_PROFILE")

    def record_operator(name: str, started: float) -> None:
        if operator_profile is None:
            return
        entry = operator_profile.setdefault(
            name, {"calls": 0, "summed_task_seconds": 0.0}
        )
        entry["calls"] = int(entry["calls"]) + 1
        entry["summed_task_seconds"] = (
            float(entry["summed_task_seconds"])
            + time.perf_counter()
            - started
        )

    preparation_started = time.perf_counter()
    source_h, source_w = records.shape[:2]
    work_w = source_w * oversample
    work_h = source_h * oversample
    native_scale = source_w / 5760.0

    log_exposure = np.log10(np.maximum(records, 1e-8)) - 1.0
    if oversample == 1:
        work_log_exposure = log_exposure.astype(np.float32)
    else:
        work_log_exposure = np.stack(
            [
                cv2.resize(
                    log_exposure[..., channel],
                    (work_w, work_h),
                    interpolation=cv2.INTER_CUBIC,
                )
                for channel in range(3)
            ],
            axis=2,
        ).astype(np.float32)

    record_operator("outer_log_exposure_preparation", preparation_started)
    if precomputed_mean_density is not None:
        if oversample != 1 or precomputed_mean_density.shape != records.shape:
            raise ValueError(
                "precomputed mean density is valid only at matching oversample=1"
            )
        mean_density = np.asarray(precomputed_mean_density, dtype=np.float32)
    else:
        mean_density = develop_5279_record_density_from_log_exposure(
            work_log_exposure
        )
    activation_started = time.perf_counter()
    activations = subemulsion_activation_probabilities(work_log_exposure)
    record_operator("outer_activation_probabilities", activation_started)
    sigma_started = time.perf_counter()
    target_sigma = published_5279_granularity_sigma(work_log_exposure)
    record_operator("outer_target_sigma", sigma_started)

    setup_started = time.perf_counter()
    work_scale = native_scale * oversample
    aperture_radius = (
        0.5
        * KODAK_GRANULARITY_APERTURE_DIAMETER_UM
        * 1e-3
        * (source_w / 24.9)
        * oversample
    )
    radii = (
        SUBEMULSION_CLOUD_RADIUS_PX_5760_RGB
        * work_scale
        * grain_scale
        * NEGATIVE_GRAIN_CORRELATION_SCALE
    )
    optical_sigmas = SUBEMULSION_OPTICAL_SIGMA_PX_5760_RGB * work_scale
    site_counts = np.maximum(
        1,
        np.rint(
            SUBEMULSION_SITE_COUNT_PX_5760_RGB
            / max(work_scale * work_scale, 1e-6)
        ).astype(np.int32),
    )
    rng = np.random.default_rng(300_000 + frame_index)
    net_capacity = SENSITO_DENSITY_RGB[:, -1] - SENSITO_DMIN_RGB
    capacities = net_capacity[:, None] * SUBEMULSION_CAPACITY_FRACTIONS[None, :]
    combined_deviation = np.zeros_like(mean_density, dtype=np.float32)
    predicted_aperture_variance = np.zeros_like(mean_density, dtype=np.float32)
    pre_dir_calibration = GRAIN_CALIBRATION_DOMAIN == "pre_dir_dye_yield"
    layer_deviation = np.zeros(
        mean_density.shape + (3,), dtype=np.float32
    )
    record_operator("outer_constants_and_allocations", setup_started)

    for channel in range(3):
        for population in range(3):
            probability_view = activations[..., channel, population]
            probability = (
                np.ascontiguousarray(probability_view, dtype=np.float32)
                if globals().get("_V27_PROBABILITY_POPULATION_CACHE", False)
                else probability_view
            )
            total_sites = int(site_counts[channel, population])
            class_fractions = (
                GRAIN_SIZE_CLASS_FRACTIONS
                if GRAIN_SIZE_CLASS_FRACTIONS_BY_POPULATION is None
                else GRAIN_SIZE_CLASS_FRACTIONS_BY_POPULATION[population]
            )
            raw_class_counts = class_fractions * total_sites
            class_counts = np.floor(raw_class_counts).astype(np.int32)
            class_counts = np.maximum(class_counts, 1)
            while int(np.sum(class_counts)) < total_sites:
                remainder = raw_class_counts - class_counts
                class_counts[int(np.argmax(remainder))] += 1
            while int(np.sum(class_counts)) > total_sites:
                removable = np.where(class_counts > 1, class_counts, 0)
                class_counts[int(np.argmax(removable))] -= 1

            population_allocation_started = time.perf_counter()
            population_deviation = np.zeros_like(probability, dtype=np.float32)
            record_operator(
                "outer_population_allocation", population_allocation_started
            )
            population_kernel_power = 0.0
            sampled_phase = float(rng.uniform(0.0, 2.0 * math.pi))
            for size_class, class_sites in enumerate(class_counts):
                class_weight = float(class_sites) / float(total_sites)
                if GRAIN_SUBPIXEL_PHASE_MODE == "frame_random":
                    angle = (
                        sampled_phase
                        + size_class * GRAIN_SIZE_CLASS_PHASE_STEP_RADIANS
                    )
                elif GRAIN_SUBPIXEL_PHASE_MODE == "stable_balanced":
                    class_identity = (
                        channel * 15 + population * 5 + size_class
                    )
                    angle = 2.0 * math.pi * (
                        (class_identity + 0.5) * GRAIN_STABLE_PHASE_STEP % 1.0
                    ) + GRAIN_STABLE_PHASE_OFFSET_RADIANS
                else:
                    raise ValueError(
                        "unknown grain subpixel phase mode: "
                        f"{GRAIN_SUBPIXEL_PHASE_MODE}"
                    )
                phase_radius = GRAIN_SUBPIXEL_PHASE_RADIUS_PX * work_scale
                subpixel_offset = (
                    phase_radius * math.cos(angle),
                    phase_radius * math.sin(angle),
                )
                class_radius = float(
                    radii[channel, population]
                    * GRAIN_SIZE_CLASS_RADIUS_FACTORS[size_class]
                )
                class_sigma = float(
                    optical_sigmas[channel, population]
                    * GRAIN_SIZE_CLASS_OPTICAL_FACTORS[size_class]
                )
                sample_seed = (
                    30_000_000
                    + int(frame_index) * 10_000
                    + channel * 1_000
                    + population * 100
                    + size_class
                )
                class_deviation = binomial_dye_cloud_deviation(
                    probability,
                    rng,
                    class_radius,
                    class_sigma,
                    int(class_sites),
                    subpixel_offset,
                    sample_seed=sample_seed,
                )
                class_accumulation_started = time.perf_counter()
                if globals().get(
                    "_WAVEFRONT_INPLACE_CLASS_ACCUMULATION", False
                ):
                    import wavefront_tile_lab_v002

                    wavefront_tile_lab_v002.weight_and_accumulate_class(
                        population_deviation,
                        class_deviation,
                        class_weight,
                    )
                else:
                    population_deviation += class_weight * class_deviation
                record_operator(
                    "outer_class_deviation_accumulation",
                    class_accumulation_started,
                )
                kernel_power_started = time.perf_counter()
                population_kernel_power += (
                    class_weight
                    * class_weight
                    * filtered_kernel_power(
                        class_radius,
                        class_sigma,
                        aperture_radius,
                        subpixel_offset,
                    )
                    / float(class_sites)
                )
                record_operator(
                    "outer_filtered_kernel_power", kernel_power_started
                )

            variance_started = time.perf_counter()
            layer_deviation[..., channel, population] = population_deviation
            capacity = float(capacities[channel, population])
            record_mix = SUBEMULSION_DYE_RECORD_MIX[population, :, channel]
            if globals().get("_V27_VARIANCE_MEMORY_REUSE", False):
                # population_deviation has already been copied into the layer
                # tensor and can become a scalar variance scratch plane. Keep
                # NumPy's original left-to-right float32 operation order while
                # avoiding the H x W x 3 broadcast temporary.
                np.multiply(
                    capacity * capacity,
                    probability,
                    out=population_deviation,
                )
                probability_complement = np.subtract(1.0, probability)
                np.multiply(
                    population_deviation,
                    probability_complement,
                    out=population_deviation,
                )
                np.multiply(
                    population_deviation,
                    population_kernel_power,
                    out=population_deviation,
                )
                record_mix_power = np.square(record_mix)
                for destination_record in range(3):
                    predicted_aperture_variance[..., destination_record] += (
                        population_deviation
                        * record_mix_power[destination_record]
                    )
            else:
                source_variance_term = (
                    capacity
                    * capacity
                    * probability
                    * (1.0 - probability)
                    * population_kernel_power
                )
                predicted_aperture_variance += (
                    source_variance_term[..., None]
                    * np.square(record_mix)[None, None, :]
                )
            record_operator(
                "outer_predicted_variance_update", variance_started
            )

    if pre_dir_calibration:
        # The published 48-um curve constrains developed dye density.  Calibrate
        # each source record's stochastic dye yield before inhibitor release so
        # stochastic DIR transports the correctly scaled chemical event.  This
        # replaces V38's post-coupling residual multiplier; it does not alter the
        # deterministic H-D mean.
        # Use the complete destination-record prediction (including spectral
        # dye-record mixing), but apply its yield scale to the corresponding
        # source record before chemistry.  Cross-record terms are deliberately
        # small; the validation gate below measures the residual after DIR.
        source_calibration = target_sigma / np.sqrt(
            np.maximum(predicted_aperture_variance, 1e-12)
        )
        for channel in range(3):
            layer_deviation[..., channel, :] *= source_calibration[
                ..., channel, None
            ]

    coupling_call_started = time.perf_counter()
    coupled_layer_deviation = couple_5279_population_deviations(
        layer_deviation, activations, work_scale
    )
    record_operator("outer_coupling_call", coupling_call_started)
    combine_started = time.perf_counter()
    scaled_deviation = (
        np.empty(mean_density.shape[:2], dtype=np.float32)
        if globals().get("_V27_RECORD_MIX_MEMORY_REUSE", False)
        else None
    )
    for channel in range(3):
        for population in range(3):
            capacity = float(capacities[channel, population])
            record_mix = SUBEMULSION_DYE_RECORD_MIX[population, :, channel]
            if scaled_deviation is not None:
                np.multiply(
                    capacity,
                    coupled_layer_deviation[..., channel, population],
                    out=scaled_deviation,
                )
                for destination_record in range(3):
                    combined_deviation[..., destination_record] += (
                        scaled_deviation * record_mix[destination_record]
                    )
            else:
                combined_deviation += (
                    capacity
                    * coupled_layer_deviation[..., channel, population, None]
                    * record_mix[None, None, :]
                )
    record_operator("outer_record_mix_accumulation", combine_started)

    # Kodak's graph is the post-process measurement. DIR/acutance is already in
    # that target, so it shapes the deterministic mean above but is not allowed
    # to boost the stochastic density a second time.
    calibration_started = time.perf_counter()
    if GRAIN_CALIBRATION_DOMAIN == "post_coupling_residual":
        calibration = target_sigma / np.sqrt(
            np.maximum(predicted_aperture_variance, 1e-12)
        )
        formed = mean_density + combined_deviation * calibration
    elif GRAIN_CALIBRATION_DOMAIN == "pre_dir_dye_yield":
        formed = mean_density + combined_deviation
    else:
        raise ValueError(
            f"unknown grain calibration domain: {GRAIN_CALIBRATION_DOMAIN}"
        )
    upper = SENSITO_DENSITY_RGB[:, -1] + 0.12
    formed = np.minimum(np.maximum(formed, 0.0), upper)
    record_operator("outer_calibration_and_clip", calibration_started)

    if oversample != 1:
        formed = np.stack(
            [
                cv2.resize(
                    formed[..., channel],
                    (source_w, source_h),
                    interpolation=cv2.INTER_AREA,
                )
                for channel in range(3)
            ],
            axis=2,
        )
    return formed.astype(np.float32)


def apply_5279_mtf(display_linear: np.ndarray, grain_scale: float) -> np.ndarray:
    """Approximate the published 5279 channel MTF at a 24.9 mm image width.

    A narrow core controls high-frequency roll-off. A difference-of-Gaussians
    band adds developer-adjacency acutance around 10-20 cycles/mm without
    preserving digital high-frequency edges. Parameters are in pixels at 5760px.
    """
    width = display_linear.shape[1]
    native_scale = (width / 5760.0) * grain_scale
    # RGB output order, corresponding approximately to published R/G/B records.
    core_sigmas = NEGATIVE_MTF_CORE_SIGMA_RGB
    adjacency_amounts = NEGATIVE_MTF_ADJACENCY_AMOUNT_RGB
    mid_sigma = NEGATIVE_MTF_ADJACENCY_MID_SIGMA_PX_5760 * native_scale
    broad_sigma = NEGATIVE_MTF_ADJACENCY_BROAD_SIGMA_PX_5760 * native_scale

    filtered = np.empty_like(display_linear)
    for channel, (core_sigma, adjacency) in enumerate(
        zip(core_sigmas, adjacency_amounts, strict=True)
    ):
        source = display_linear[..., channel]
        core = cv2.GaussianBlur(
            source,
            (0, 0),
            max(core_sigma * native_scale, 0.05),
            borderType=cv2.BORDER_REFLECT,
        )
        mid = cv2.GaussianBlur(
            source, (0, 0), max(mid_sigma, 0.05), borderType=cv2.BORDER_REFLECT
        )
        broad = cv2.GaussianBlur(
            source,
            (0, 0),
            max(broad_sigma, 0.05),
            borderType=cv2.BORDER_REFLECT,
        )
        filtered[..., channel] = core + adjacency * (mid - broad)
    return np.clip(filtered, 0.0, 1.0)


def apply_5279_mtf_to_record_density(
    record_density: np.ndarray, grain_scale: float
) -> np.ndarray:
    """Apply Kodak's processed-stock MTF to negative density modulation.

    H-1-5279 reports the response of an exposed and ECN-2 processed negative,
    not a display-positive RGB image.  The V39 path therefore performs the same
    fitted core/adjacency transfer before spectral scanning or optical printing.
    Signed edge excursions are retained; downstream density observers already
    own their physical bounds and D-min treatment.
    """
    width = record_density.shape[1]
    native_scale = (width / 5760.0) * grain_scale
    mid_sigma = NEGATIVE_MTF_ADJACENCY_MID_SIGMA_PX_5760 * native_scale
    broad_sigma = NEGATIVE_MTF_ADJACENCY_BROAD_SIGMA_PX_5760 * native_scale
    filtered = np.empty_like(record_density, dtype=np.float32)
    for channel, (core_sigma, adjacency) in enumerate(
        zip(NEGATIVE_MTF_CORE_SIGMA_RGB, NEGATIVE_MTF_ADJACENCY_AMOUNT_RGB, strict=True)
    ):
        source = np.asarray(record_density[..., channel], dtype=np.float32)
        core = cv2.GaussianBlur(
            source, (0, 0), max(core_sigma * native_scale, 0.05),
            borderType=cv2.BORDER_REFLECT,
        )
        mid = cv2.GaussianBlur(
            source, (0, 0), max(mid_sigma, 0.05), borderType=cv2.BORDER_REFLECT
        )
        broad = cv2.GaussianBlur(
            source, (0, 0), max(broad_sigma, 0.05), borderType=cv2.BORDER_REFLECT
        )
        filtered[..., channel] = core + adjacency * (mid - broad)
    return filtered.astype(np.float32)


def apply_2383_mtf(display_linear: np.ndarray, grain_scale: float) -> np.ndarray:
    """Add the fine, channel-dependent MTF of the physical 2383 print stage."""
    native_scale = (display_linear.shape[1] / 5760.0) * grain_scale
    # The published print-film graph orders green > red > blue at high spatial
    # frequencies. The modest kernels preserve its fine 35 mm character while
    # ensuring that print grain and sharpness still describe the same medium.
    sigmas_rgb = (0.34, 0.27, 0.52)
    filtered = np.empty_like(display_linear)
    for channel, sigma in enumerate(sigmas_rgb):
        filtered[..., channel] = cv2.GaussianBlur(
            display_linear[..., channel],
            (0, 0),
            max(sigma * native_scale, 0.05),
            borderType=cv2.BORDER_REFLECT,
        )
    return np.clip(filtered, 0.0, 1.0)


