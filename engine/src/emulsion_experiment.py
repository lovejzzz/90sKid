def linear_rec709_to_oklab(rgb: np.ndarray) -> np.ndarray:
    """Convert linear Rec.709 RGB to OKLab for perceptual colour calibration."""
    rgb_to_lms = np.array(
        [
            [0.4122214708, 0.5363325363, 0.0514459929],
            [0.2119034982, 0.6806995451, 0.1073969566],
            [0.0883024619, 0.2817188376, 0.6299787005],
        ],
        dtype=np.float32,
    )
    lms_to_lab = np.array(
        [
            [0.2104542553, 0.7936177850, -0.0040720468],
            [1.9779984951, -2.4285922050, 0.4505937099],
            [0.0259040371, 0.7827717662, -0.8086757660],
        ],
        dtype=np.float32,
    )
    lms = np.einsum("...c,dc->...d", np.maximum(rgb, 0.0), rgb_to_lms)
    return np.einsum(
        "...c,dc->...d", np.cbrt(np.maximum(lms, 0.0)), lms_to_lab
    ).astype(np.float32)


def oklab_to_linear_rec709(lab: np.ndarray) -> np.ndarray:
    """Convert OKLab to linear Rec.709 RGB."""
    lab_to_lms_root = np.array(
        [
            [1.0, 0.3963377774, 0.2158037573],
            [1.0, -0.1055613458, -0.0638541728],
            [1.0, -0.0894841775, -1.2914855480],
        ],
        dtype=np.float32,
    )
    lms_to_rgb = np.array(
        [
            [4.0767416621, -3.3077115913, 0.2309699292],
            [-1.2684380046, 2.6097574011, -0.3413193965],
            [-0.0041960863, -0.7034186147, 1.7076147010],
        ],
        dtype=np.float32,
    )
    lms_root = np.einsum("...c,dc->...d", lab, lab_to_lms_root)
    return np.einsum("...c,dc->...d", lms_root**3, lms_to_rgb).astype(
        np.float32
    )


def compress_oklab_chroma_to_rec709(
    rgb: np.ndarray,
    lower_bound: float = 0.0,
) -> np.ndarray:
    """Fit extended RGB into Rec.709 while preserving OKLab lightness and hue.

    The former luma-axis RGB compressor could rotate very dark reds toward
    magenta by tens of degrees. Only out-of-gamut samples are processed here;
    eight bisection steps reduce OKLab chroma until the original hue fits.
    """
    source = np.asarray(rgb, dtype=np.float32)
    result = source.copy()
    out = np.any((source < lower_bound) | (source > 1.0), axis=-1)
    if not np.any(out):
        return result

    extended = source[out]
    lab = linear_rec709_to_oklab(extended)
    lab[:, 0] = np.clip(lab[:, 0], 0.0, 1.0)
    low = np.zeros(lab.shape[0], dtype=np.float32)
    high = np.ones(lab.shape[0], dtype=np.float32)
    for _ in range(8):
        scale = 0.5 * (low + high)
        candidate_lab = lab.copy()
        candidate_lab[:, 1:3] *= scale[:, None]
        candidate = oklab_to_linear_rec709(candidate_lab)
        fits = np.all(
            (candidate >= lower_bound) & (candidate <= 1.0), axis=1
        )
        low = np.where(fits, scale, low)
        high = np.where(fits, high, scale)
    lab[:, 1:3] *= low[:, None]
    result[out] = oklab_to_linear_rec709(lab)
    # ``result`` is already an owned float32 buffer.  Clipping it in place
    # preserves every code value while avoiding two complete image copies
    # (one from ``clip`` and another from ``astype``) at this frequent boundary.
    np.clip(result, lower_bound, 1.0, out=result)
    return result


def smoothstep(edge0: float, edge1: float, value: np.ndarray) -> np.ndarray:
    t = np.clip((value - edge0) / (edge1 - edge0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def film_positive_luminance(scene_luma: np.ndarray) -> np.ndarray:
    """Map scene reflection through a long-toe/long-shoulder negative-print pair.

    The curve is anchored so scene-linear 18% gray remains 18% display-linear.
    Unlike a video clamp it approaches white asymptotically, retaining several
    stops above diffuse white for the emulsion shoulder to compress.
    """
    scene_luma = np.clip(scene_luma, 0.0, None)
    power = 0.92
    mid_gray = 0.18
    coefficient = -math.log(1.0 - mid_gray) / (mid_gray**power)
    return 1.0 - np.exp(-coefficient * np.power(scene_luma, power))


def vlog_encode(scene_linear: np.ndarray) -> np.ndarray:
    """Panasonic V-Log encoding for diagnostics, not a baked RAW assumption."""
    scene_linear = np.clip(scene_linear, 0.0, None)
    return np.where(
        scene_linear < 0.01,
        5.6 * scene_linear + 0.125,
        0.241514 * np.log10(scene_linear + 0.00873) + 0.598206,
    ).astype(np.float32)


def vlog_decode(vlog: np.ndarray) -> np.ndarray:
    """Invert Panasonic's published V-Log transfer function."""
    vlog = np.asarray(vlog, dtype=np.float32)
    return np.where(
        vlog < 0.181,
        (vlog - 0.125) / 5.6,
        np.power(10.0, (vlog - 0.598206) / 0.241514) - 0.00873,
    ).astype(np.float32)


def load_panasonic_raw_to_vgamut_lut() -> np.ndarray:
    """Load Panasonic's GH7-compatible RAW Gamut to V-Gamut camera LUT."""
    global _PANASONIC_RAW_TO_VGAMUT_LUT
    if _PANASONIC_RAW_TO_VGAMUT_LUT is not None:
        return _PANASONIC_RAW_TO_VGAMUT_LUT

    size = None
    values: list[list[float]] = []
    for line in PANASONIC_RAW_TO_VGAMUT_LUT_PATH.read_text().splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.startswith("LUT_3D_SIZE"):
            size = int(stripped.split()[1])
            continue
        if stripped.startswith(("TITLE", "DOMAIN_", "LUT_1D_SIZE")):
            continue
        fields = stripped.split()
        if len(fields) == 3:
            values.append([float(value) for value in fields])
    if size is None or len(values) != size**3:
        raise ValueError(
            f"invalid Panasonic camera LUT: {PANASONIC_RAW_TO_VGAMUT_LUT_PATH}"
        )

    # .cube ordering is red-fastest, then green, then blue.
    _PANASONIC_RAW_TO_VGAMUT_LUT = np.asarray(values, dtype=np.float32).reshape(
        size, size, size, 3
    )
    return _PANASONIC_RAW_TO_VGAMUT_LUT


def apply_rgb_cube_lut(
    rgb: np.ndarray, lut: np.ndarray, rows_per_stripe: int = 96
) -> np.ndarray:
    """Trilinearly sample a standard red-fastest .cube without large temporaries."""
    size = lut.shape[0]
    result = np.empty_like(rgb, dtype=np.float32)
    for row0 in range(0, rgb.shape[0], rows_per_stripe):
        row1 = min(row0 + rows_per_stripe, rgb.shape[0])
        scaled = np.clip(rgb[row0:row1], 0.0, 1.0) * (size - 1)
        lower = np.floor(scaled).astype(np.int16)
        fraction = scaled - lower
        upper = np.minimum(lower + 1, size - 1)
        r0, g0, b0 = lower[..., 0], lower[..., 1], lower[..., 2]
        r1, g1, b1 = upper[..., 0], upper[..., 1], upper[..., 2]
        fr, fg, fb = fraction[..., 0:1], fraction[..., 1:2], fraction[..., 2:3]

        # LUT axes are blue, green, red after reshaping red-fastest data.
        c000 = lut[b0, g0, r0]
        c100 = lut[b0, g0, r1]
        c010 = lut[b0, g1, r0]
        c110 = lut[b0, g1, r1]
        c001 = lut[b1, g0, r0]
        c101 = lut[b1, g0, r1]
        c011 = lut[b1, g1, r0]
        c111 = lut[b1, g1, r1]
        c00 = c000 * (1.0 - fr) + c100 * fr
        c10 = c010 * (1.0 - fr) + c110 * fr
        c01 = c001 * (1.0 - fr) + c101 * fr
        c11 = c011 * (1.0 - fr) + c111 * fr
        c0 = c00 * (1.0 - fg) + c10 * fg
        c1 = c01 * (1.0 - fg) + c11 * fg
        result[row0:row1] = c0 * (1.0 - fb) + c1 * fb
    return result


def panasonic_raw_to_vgamut(scene_linear: np.ndarray) -> np.ndarray:
    """Apply Panasonic's RAW-Gamut camera LUT to a RAW-Gamut-stage buffer.

    This legacy/diagnostic path is valid only when the decoder explicitly
    supplies Panasonic RAW Gamut at the Camera-LUT boundary. It must not be
    used for AVFoundation's already converted extended-linear BT.2020 buffer;
    V28 routes that buffer through ``bt2020_to_panasonic_vgamut`` instead.
    """
    encoded = vlog_encode(scene_linear)
    transformed = apply_rgb_cube_lut(encoded, load_panasonic_raw_to_vgamut_lut())
    return np.maximum(vlog_decode(transformed), 0.0).astype(np.float32)


def bt2020_to_panasonic_vgamut(scene_linear: np.ndarray) -> np.ndarray:
    """Put Apple's extended-linear BT.2020 RAW rendering into V-Gamut.

    AVFoundation has already applied the ProRes RAW standard conversion and
    identifies this RGB buffer as extended-linear BT.2020/D65.  A primary
    conversion is therefore the complete gamut step.  Panasonic's separate
    RAW-Gamut camera LUT must not be applied to this already converted buffer.
    """
    xyz = np.einsum("...c,dc->...d", scene_linear, BT2020_TO_XYZ_D65)
    return np.einsum("...c,dc->...d", xyz, XYZ_D65_TO_VGAMUT)


def vgamut_to_balanced_film_rgb(vgamut: np.ndarray) -> np.ndarray:
    """Convert D65 V-Gamut to a neutral, 3200 K-balanced virtual stock input."""
    xyz = np.einsum("...c,dc->...d", vgamut, VGAMUT_TO_XYZ_D65)
    rec709 = np.einsum("...c,dc->...d", xyz, XYZ_D65_TO_REC709)
    if FILM_RECORD_BOUNDARY_MODE == "basis_clip":
        rec709 = np.clip(rec709, 0.0, None)
    return rec709.astype(np.float32)


def bt2020_to_balanced_film_rgb(scene_linear: np.ndarray) -> np.ndarray:
    """Fuse the algebraically cancelling V-Gamut round trip.

    This uses the product of the exact matrices used by the legacy path.  It is
    a primary conversion only; white balance remains owned by Apple's standard
    ProRes RAW conversion upstream.
    """
    source = np.asarray(scene_linear, dtype=np.float32)
    if source.ndim == 3 and source.shape[-1] == 3:
        converted = cv2.transform(source, AVFOUNDATION_BT2020_TO_FILM_RGB)
    else:
        converted = np.einsum(
            "...c,dc->...d", source, AVFOUNDATION_BT2020_TO_FILM_RGB
        )
    if FILM_RECORD_BOUNDARY_MODE == "basis_clip":
        converted = np.clip(converted, 0.0, None)
    return converted.astype(np.float32)


def film_records_from_rgb(film_rgb: np.ndarray) -> np.ndarray:
    source = np.asarray(film_rgb, dtype=np.float32)
    records = np.einsum(
        "...c,dc->...d", source, FILM_RECORD_SENSITIVITY_RGB
    ).astype(np.float32)
    if FILM_RECORD_BOUNDARY_MODE == "record_positive_signed":
        clipped_records = np.einsum(
            "...c,dc->...d",
            np.maximum(source, 0.0),
            FILM_RECORD_SENSITIVITY_RGB,
        ).astype(np.float32)
        valid_signed = np.all(records >= 0.0, axis=-1, keepdims=True)
        records = np.where(valid_signed, records, clipped_records)
        records = np.maximum(records, 0.0)
    elif FILM_RECORD_BOUNDARY_MODE == "signed":
        # Tristimulus basis components may be signed; physical exposure records
        # may not.  Clamp once, after the stock sensitivity matrix has combined
        # the basis, rather than independently clipping its inputs.
        records = np.maximum(records, 0.0)
    elif FILM_RECORD_BOUNDARY_MODE != "basis_clip":
        raise ValueError(
            f"unknown film record boundary mode: {FILM_RECORD_BOUNDARY_MODE}"
        )
    return records


def apply_input_chroma_residual(scene_linear: np.ndarray) -> np.ndarray:
    """Apply V41's neutral- and luminance-preserving input residual.

    The matrix is a cross-group DKC-Pro diagnostic, not a creative look.  It is
    expressed in Bradford-adapted D50 XYZ because the manufacturer's published
    Lab triplets omit an illuminant/observer declaration.  The profile limits
    authority to chroma: D65-neutral RGB and adapted Y are identities.
    """
    source = np.asarray(scene_linear, dtype=np.float32)
    if not INPUT_CHROMA_RESIDUAL_ENABLED or INPUT_CHROMA_RESIDUAL_STRENGTH == 0.0:
        return source.copy()
    xyz_d65 = np.einsum("...c,dc->...d", source, BT2020_TO_XYZ_D65)
    xyz_d50 = np.einsum("...c,dc->...d", xyz_d65, _BRADFORD_D65_TO_D50)
    luminance = xyz_d50[..., 1]
    neutral = luminance[..., None] * D50_XYZ
    chroma = xyz_d50 - neutral
    mapped = np.einsum("...c,cd->...d", chroma, INPUT_CHROMA_RESIDUAL_D50)
    corrected_chroma = chroma + INPUT_CHROMA_RESIDUAL_STRENGTH * (mapped - chroma)
    # The fit is chromaticity-only.  Remove floating-point/ridge leakage into Y
    # instead of turning the chart residual into a hidden gamma or exposure move.
    corrected_chroma[..., 1] = 0.0
    corrected_d50 = neutral + corrected_chroma
    corrected_d65 = np.einsum(
        "...c,dc->...d", corrected_d50, _BRADFORD_D50_TO_D65
    )
    # Preserve the original scene-referred D65 luminance exactly.  This also
    # protects highlight headroom because no unit-range clamp is introduced.
    scale = xyz_d65[..., 1] / np.where(
        np.abs(corrected_d65[..., 1]) > 1e-8,
        corrected_d65[..., 1],
        np.copysign(1e-8, corrected_d65[..., 1] + 1e-12),
    )
    corrected_d65 *= scale[..., None]
    return np.einsum(
        "...c,dc->...d", corrected_d65, np.linalg.inv(BT2020_TO_XYZ_D65)
    ).astype(np.float32)


def record_densities(records: np.ndarray) -> np.ndarray:
    """Apply separate 5279 red/green/blue H-D curves in log exposure."""
    log_exposure = np.log10(np.maximum(records, 1e-8)) - 1.0
    return record_densities_from_log_exposure(log_exposure)


def record_densities_from_log_exposure(log_exposure: np.ndarray) -> np.ndarray:
    """Sample 5279 H-D curves with neutral-preserving sublayer crossover.

    The three published curves remain the exact response along the neutral
    exposure axis. Away from that axis, marginal fast/medium/slow activation
    weights choose a restrained record-mixing matrix. This makes colour
    separation slightly less complete in a thin, fast-grain-dominated negative
    and nearly record-pure where the small slow population carries highlights.
    """
    densities = np.empty_like(log_exposure, dtype=np.float32)
    for channel in range(3):
        densities[..., channel] = np.interp(
            log_exposure[..., channel],
            SENSITO_LOG_EXPOSURE,
            SENSITO_DENSITY_RGB[channel],
        ).astype(np.float32)

    neutral_log_exposure = np.mean(log_exposure, axis=-1, keepdims=True)
    neutral_density = np.empty_like(densities, dtype=np.float32)
    for channel in range(3):
        neutral_density[..., channel] = np.interp(
            neutral_log_exposure[..., 0],
            SENSITO_LOG_EXPOSURE,
            SENSITO_DENSITY_RGB[channel],
        ).astype(np.float32)

    centres = (
        SUBEMULSION_FAST_CENTRE_LOGE_RGB[:, None]
        + SUBEMULSION_SPEED_OFFSETS_LOGE[None, :]
    )
    widths = SUBEMULSION_TRANSITION_WIDTH_RGB[:, None]
    argument = (log_exposure[..., :, None] - centres) / widths
    argument = np.clip(argument, -16.0, 16.0)
    activations = (1.0 / (1.0 + np.exp(-argument))).astype(np.float32)
    marginal = (
        activations
        * (1.0 - activations)
        * SUBEMULSION_CAPACITY_FRACTIONS
        / widths
    )
    marginal /= np.maximum(np.sum(marginal, axis=-1, keepdims=True), 1e-8)
    # Each source record chooses its own mixture according to which speed layer
    # is carrying incremental density at that exposure.
    effective_mix = np.einsum(
        "...sp,pds->...ds", marginal, SUBEMULSION_DYE_RECORD_MIX
    )
    chromatic_departure = densities - neutral_density
    mixed_departure = np.einsum(
        "...s,...ds->...d", chromatic_departure, effective_mix
    )
    return (neutral_density + mixed_departure).astype(np.float32)


def _negative_5279_status_m_weights() -> np.ndarray:
    """Narrow Status-M-like bands used only for Kodak density calibration."""
    wavelength = NEGATIVE_DYE_WAVELENGTHS_NM[:, None]
    centres = np.array([690.0, 550.0, 450.0], dtype=np.float32)[None, :]
    sigmas = np.array([22.0, 19.0, 17.0], dtype=np.float32)[None, :]
    weights = np.exp(-0.5 * np.square((wavelength - centres) / sigmas))
    return (weights / np.sum(weights, axis=0, keepdims=True)).astype(np.float32)


def _negative_5279_period_telecine_weights() -> np.ndarray:
    """Broad period RGB telecine observer, distinct from Status-M.

    Contemporary Kodak work plots a typical electronic-transfer observer near
    620/540/470 nm with broad overlap. These bounded Gaussian fits are not a
    proprietary Spirit spectral disclosure; they deliberately retain the
    cross-talk that the scanner's later optical-film-match matrix must correct.
    """
    wavelength = NEGATIVE_DYE_WAVELENGTHS_NM[:, None]
    centres = np.asarray(
        SPIRIT_PERIOD_OBSERVER_CENTRES_NM, dtype=np.float32
    )[None, :]
    sigmas = np.asarray(
        SPIRIT_PERIOD_OBSERVER_SIGMAS_NM, dtype=np.float32
    )[None, :]
    weights = np.exp(-0.5 * np.square((wavelength - centres) / sigmas))
    return (weights / np.sum(weights, axis=0, keepdims=True)).astype(np.float32)


def _negative_5279_spectral_amount_axes(
    size: int,
) -> tuple[np.ndarray, np.ndarray, list[np.ndarray]]:
    """Return Status-M axes and spectral dye amounts for the 5279 records."""
    weights = _negative_5279_status_m_weights()
    spectra = NEGATIVE_5279_NET_DYE_CMY_SPECTRAL_DENSITY.copy()
    own_band_density = np.sum(weights * spectra, axis=0)
    spectra /= np.maximum(own_band_density, 1e-5)[None, :]

    axis = np.linspace(
        0.0, NEGATIVE_5279_MAX_RECORD_DENSITY, size, dtype=np.float32
    )
    # The input H-D values are already Status-M densities. Solve a separate
    # spectral amount shaper for each record so a pure cyan/magenta/yellow
    # separation preserves that measured density in its own R/G/B band.
    coefficient_grid = np.linspace(0.0, 12.0, 4097, dtype=np.float32)
    coefficient_axes = []
    with np.errstate(all="ignore"):
        for channel in range(3):
            single_transmission = np.power(
                10.0,
                -coefficient_grid[:, None] * spectra[:, channel][None, :],
            )
            own_transmission = single_transmission @ weights[:, channel]
            own_density = -np.log10(np.maximum(own_transmission, 1e-8))
            coefficient_axes.append(
                np.interp(axis, own_density, coefficient_grid).astype(np.float32)
            )
    return axis, spectra, coefficient_axes


def build_5279_net_density_lut(size: int = 29) -> np.ndarray:
    """Build period-telecine RGB density from signed 5279 net spectra.

    Spectral dye amounts are calibrated against their own narrow Status-M band,
    but acquisition is integrated through the broader, differently centred
    period-telecine observer. The residual shape, including masking-coupler
    cancellation, therefore creates genuine scanner cross-talk before primary
    correction instead of conflating measurement with acquisition.
    """
    weights = _negative_5279_period_telecine_weights()
    _, spectra, coefficient_axes = _negative_5279_spectral_amount_axes(size)

    cyan, magenta, yellow = np.meshgrid(
        coefficient_axes[0], coefficient_axes[1], coefficient_axes[2],
        indexing="ij",
    )
    cmy = np.stack([cyan, magenta, yellow], axis=-1).reshape(-1, 3)
    with np.errstate(all="ignore"):
        spectral_density = np.clip(cmy @ spectra.T, -2.0, 16.0)
        transmission = np.power(10.0, -spectral_density)
        rgb_transmission = transmission @ weights
    return (-np.log10(np.maximum(rgb_transmission, 1e-8))).reshape(
        size, size, size, 3
    ).astype(np.float32)


def build_5279_to_2383_printer_density_lut(size: int = 29) -> np.ndarray:
    """Integrate 5279 transmission against the three broad 2383 records.

    The effective density seen by print record j is
    -log10(integral(Lprinter * Tnegative * S2383_j)). A 3200 K tungsten printer
    spectrum follows the exposure condition in H-1-2383. Per-record printer
    lights subsequently place an 18% negative on LAD, so only the spectral
    shape—not an invented absolute print speed—is required here.
    """
    _, spectra, coefficient_axes = _negative_5279_spectral_amount_axes(size)
    cyan, magenta, yellow = np.meshgrid(
        coefficient_axes[0], coefficient_axes[1], coefficient_axes[2],
        indexing="ij",
    )
    cmy = np.stack([cyan, magenta, yellow], axis=-1).reshape(-1, 3)

    lamp = _blackbody_spd(NEGATIVE_DYE_WAVELENGTHS_NM, 3200.0)
    sensitivity = np.power(10.0, PRINT_2383_LOG_SENSITIVITY_CMY)
    exposure_weights = lamp[:, None] * sensitivity
    exposure_weights /= np.maximum(
        np.sum(exposure_weights, axis=0, keepdims=True), 1e-12
    )

    with np.errstate(all="ignore"):
        spectral_density = (
            NEGATIVE_5279_DMIN_SPECTRAL_DENSITY[None, :]
            + cmy @ spectra.T
        )
        spectral_density = np.clip(spectral_density, 0.0, 16.0)
        transmission = np.power(10.0, -spectral_density)
        print_record_transmission = transmission @ exposure_weights
        printer_density = -np.log10(
            np.maximum(print_record_transmission, 1e-12)
        )
    return printer_density.reshape(size, size, size, 3).astype(np.float32)


def apply_5279_net_density_lut(net_record_density: np.ndarray) -> np.ndarray:
    """Sample the signed 5279 masking model for arbitrary RGB record arrays."""
    global _NEGATIVE_5279_NET_DENSITY_LUT
    if _NEGATIVE_5279_NET_DENSITY_LUT is None:
        _NEGATIVE_5279_NET_DENSITY_LUT = build_5279_net_density_lut()
    lut = _NEGATIVE_5279_NET_DENSITY_LUT
    size = lut.shape[0]
    flat = np.asarray(net_record_density, dtype=np.float32).reshape(-1, 3)
    result = np.empty_like(flat)

    # Chunking keeps full 5.7K open-gate frames within practical memory.
    for start in range(0, flat.shape[0], 500_000):
        stop = min(start + 500_000, flat.shape[0])
        scaled = np.clip(
            flat[start:stop]
            * ((size - 1) / NEGATIVE_5279_MAX_RECORD_DENSITY),
            0.0,
            size - 1.00001,
        )
        lower = np.floor(scaled).astype(np.int16)
        fraction = scaled - lower
        upper = np.minimum(lower + 1, size - 1)
        c0, m0, y0 = lower[:, 0], lower[:, 1], lower[:, 2]
        c1, m1, y1 = upper[:, 0], upper[:, 1], upper[:, 2]
        fc, fm, fy = fraction[:, 0:1], fraction[:, 1:2], fraction[:, 2:3]

        c00 = lut[c0, m0, y0] * (1.0 - fc) + lut[c1, m0, y0] * fc
        c01 = lut[c0, m0, y1] * (1.0 - fc) + lut[c1, m0, y1] * fc
        c10 = lut[c0, m1, y0] * (1.0 - fc) + lut[c1, m1, y0] * fc
        c11 = lut[c0, m1, y1] * (1.0 - fc) + lut[c1, m1, y1] * fc
        c0y = c00 * (1.0 - fy) + c01 * fy
        c1y = c10 * (1.0 - fy) + c11 * fy
        result[start:stop] = c0y * (1.0 - fm) + c1y * fm
    return result.reshape(np.asarray(net_record_density).shape).astype(np.float32)


def apply_5279_to_2383_printer_density_lut(
    net_record_density: np.ndarray,
) -> np.ndarray:
    """Sample effective 2383-record densities through the full 5279 spectrum."""
    global _NEGATIVE_5279_TO_2383_PRINTER_DENSITY_LUT
    if _NEGATIVE_5279_TO_2383_PRINTER_DENSITY_LUT is None:
        _NEGATIVE_5279_TO_2383_PRINTER_DENSITY_LUT = (
            build_5279_to_2383_printer_density_lut()
        )
    lut = _NEGATIVE_5279_TO_2383_PRINTER_DENSITY_LUT
    size = lut.shape[0]
    source = np.asarray(net_record_density, dtype=np.float32)
    flat = source.reshape(-1, 3)
    result = np.empty_like(flat)

    for start in range(0, flat.shape[0], 500_000):
        stop = min(start + 500_000, flat.shape[0])
        scaled = np.clip(
            flat[start:stop]
            * ((size - 1) / NEGATIVE_5279_MAX_RECORD_DENSITY),
            0.0,
            size - 1.00001,
        )
        lower = np.floor(scaled).astype(np.int16)
        fraction = scaled - lower
        upper = np.minimum(lower + 1, size - 1)
        c0, m0, y0 = lower[:, 0], lower[:, 1], lower[:, 2]
        c1, m1, y1 = upper[:, 0], upper[:, 1], upper[:, 2]
        fc, fm, fy = fraction[:, 0:1], fraction[:, 1:2], fraction[:, 2:3]

        c00 = lut[c0, m0, y0] * (1.0 - fc) + lut[c1, m0, y0] * fc
        c01 = lut[c0, m0, y1] * (1.0 - fc) + lut[c1, m0, y1] * fc
        c10 = lut[c0, m1, y0] * (1.0 - fc) + lut[c1, m1, y0] * fc
        c11 = lut[c0, m1, y1] * (1.0 - fc) + lut[c1, m1, y1] * fc
        c0y = c00 * (1.0 - fy) + c01 * fy
        c1y = c10 * (1.0 - fy) + c11 * fy
        result[start:stop] = c0y * (1.0 - fm) + c1y * fm
    return result.reshape(source.shape).astype(np.float32)


def scanner_density_from_film_rgb(film_rgb: np.ndarray) -> np.ndarray:
    records = film_records_from_rgb(film_rgb)
    total_density = develop_5279_record_density(records)
    return scanner_density_from_total_record_density(total_density)


def scanner_density_from_total_record_density(
    total_density: np.ndarray,
) -> np.ndarray:
    """Convert already formed 5279 record density to a Spirit-like RGB scan."""
    # D-min is a calibrated field average. Microscopic base/fog fluctuations can
    # legitimately fall slightly below it; AutoDmin removes the mean, not those
    # local negative deviations. The spectral LUT handles formed positive dye,
    # while Spirit primary correction carries the small signed residual.
    signed_net_density = total_density - SENSITO_DMIN_RGB
    positive_net_density = np.maximum(signed_net_density, 0.0)
    optical_density = apply_5279_net_density_lut(positive_net_density)
    # The Spirit does not deliver uncorrected CCD dye cross-talk. Its optical
    # film matching and RGB primary correction move the measured densities back
    # toward independent record densities before the creative grade. Preserve a
    # restrained residual because the proprietary stock-specific matrix is not
    # published and its correction is not perfectly spectral/nonlinear.
    mean_positive_density = np.mean(positive_net_density, axis=-1)
    shoulder = smoothstep(
        float(SPIRIT_PRIMARY_CORRECTION_SHOULDER_DENSITY[0]),
        float(SPIRIT_PRIMARY_CORRECTION_SHOULDER_DENSITY[1]),
        mean_positive_density,
    )
    correction_strength = (
        SPIRIT_PRIMARY_CORRECTION_STRENGTH
        - SPIRIT_PRIMARY_CORRECTION_SHOULDER_RELEASE * shoulder
    )
    return (
        optical_density
        + correction_strength[..., None]
        * (signed_net_density - optical_density)
    ).astype(np.float32)


def negative_total_printer_density(film_rgb: np.ndarray) -> np.ndarray:
    """5279 Status-M density seen by a three-colour optical printer.

    D-min/orange-mask density remains in the printer light path. The developed
    record above D-min is converted through the signed net spectral curves, so
    coloured-coupler masking is represented once, not as an added positive dye
    tail and not as a second synthetic orange mask.
    """
    total_density = develop_5279_record_density(
        film_records_from_rgb(film_rgb)
    )
    return negative_total_printer_density_from_record_density(total_density)


def negative_total_printer_density_from_record_density(
    total_density: np.ndarray,
) -> np.ndarray:
    """Convert already formed 5279 record density to optical-printer density."""
    signed_net_density = total_density - SENSITO_DMIN_RGB
    positive_net_density = np.maximum(signed_net_density, 0.0)
    printer_density = apply_5279_to_2383_printer_density_lut(
        positive_net_density
    )
    # Carry microscopic below-average base/fog deviations without pretending
    # that a negative spectral density exists. The mean D-min spectrum is
    # already inside the LUT and is therefore integrated exactly once.
    return (
        printer_density + np.minimum(signed_net_density, 0.0)
    ).astype(np.float32)


def _inverse_2383_density(channel: int, density: float) -> float:
    return float(
        np.interp(
            density,
            PRINT_2383_DENSITY_RGB[channel],
            PRINT_2383_LOG_EXPOSURE,
        )
    )


def _raw_print_2383_density_from_negative(
    negative_density_rgb: np.ndarray,
) -> np.ndarray:
    """Expose 2383 through the 5279 negative using neutral LAD printer lights."""
    neutral_negative = negative_total_printer_density(
        np.array([0.18, 0.18, 0.18], dtype=np.float32)
    )
    aim_log_exposure = np.array(
        [
            _inverse_2383_density(
                channel, float(PRINT_2383_LAD_STATUS_A_AIM_RGB[channel])
            )
            for channel in range(3)
        ],
        dtype=np.float32,
    )
    printer_log_light = neutral_negative + aim_log_exposure
    captured_log_exposure = printer_log_light - negative_density_rgb
    print_log_exposure = (
        aim_log_exposure
        + np.einsum(
            "...c,dc->...d",
            captured_log_exposure - aim_log_exposure,
            PRINT_2383_INTERIMAGE_MATRIX,
        )
    ).astype(np.float32)

    density = np.empty_like(print_log_exposure, dtype=np.float32)
    for channel in range(3):
        density[..., channel] = np.interp(
            print_log_exposure[..., channel],
            PRINT_2383_LOG_EXPOSURE,
            PRINT_2383_DENSITY_RGB[channel],
        ).astype(np.float32)
    return density


def _build_2383_neutral_shapers() -> tuple[list[np.ndarray], list[np.ndarray]]:
    """Fit per-record shapers to Kodak's six-step neutral-scale calibration idea.

    A single LAD patch only fixes the gray point. Small graph-digitization errors
    in the negative and print gammas otherwise become large colour crossovers at
    the ends of 2383's steep scale. Kodak H-61 explicitly calls for adjusting
    contrast until every step of the gray scale remains neutral. These 1D
    shapers implement that calibration while leaving non-neutral record
    separations, and therefore film colour interactions, intact.
    """
    stops = np.linspace(-12.0, 9.0, 337, dtype=np.float32)
    levels = 0.18 * np.power(2.0, stops)
    neutral = np.repeat(levels[:, None], 3, axis=1).astype(np.float32)
    raw = _raw_print_2383_density_from_negative(
        negative_total_printer_density(neutral)
    )
    # H-61B's visual-neutral 2383 LAD does not have equal Status-A readings:
    # 1.09 R, 1.06 G and 1.03 B.  Preserve the selected profile's relative
    # record placement while correcting graph-digitization crossover along the
    # scale.  Legacy equal-aim profiles reduce exactly to the former mean curve.
    aim_mean = np.mean(raw, axis=1)
    lad_aim = np.asarray(
        PRINT_2383_LAD_STATUS_A_AIM_RGB, dtype=np.float32
    )
    aim = aim_mean[:, None] + (lad_aim - np.mean(lad_aim))[None, :]
    x_tables = []
    y_tables = []
    for channel in range(3):
        order = np.argsort(raw[:, channel])
        x = raw[order, channel]
        y = aim[order, channel]
        x, unique_indices = np.unique(x, return_index=True)
        y = y[unique_indices]
        x_tables.append(x.astype(np.float32))
        y_tables.append(y.astype(np.float32))
    return x_tables, y_tables


def print_2383_density_from_negative(
    negative_density_rgb: np.ndarray,
) -> np.ndarray:
    """Return gray-scale calibrated 2383 Status-A densities."""
    global _PRINT_2383_NEUTRAL_SHAPERS
    if _PRINT_2383_NEUTRAL_SHAPERS is None:
        _PRINT_2383_NEUTRAL_SHAPERS = _build_2383_neutral_shapers()
